#!/usr/bin/env node
/**
 * sync-koi-api.mjs —— 把 ashu 的 API 配置整体同步给 koi（2026-11-16 主人定）。
 *
 * **全同步**：provider 定义 + 模型选择 + 凭据，全部以 ashu 为准。
 * 她的 API 从此不自己维护——一处改，两边一致。
 *
 * 同步什么：
 *   1. provider 定义  ← ashu web profile 里的 `llm-pi-ai.config.providers`
 *                       写到她的 `<koi>/.dsh-home/profiles/koi/llm-providers.yml`
 *   2. 模型选择      ← ashu 的 MODEL_PROVIDER / MODEL_NAME / MODEL_REASONING_EFFORT
 *                       写进她的 `.env`（守护插件也会在拉起时传下去，这里是落盘备份）
 *   3. 凭据          ← ashu `.dsh/.credentials.yaml` 的 refs 里，被上面 provider 引用到的
 *                       那些 apiKeyEnv，整条抄进她的 `.credentials.yaml`
 *
 * 为什么凭据也要同步：provider 换了但 key 没跟，症状是「provider 加载了但一调就 401」，
 * 而且从她的日志里看不出来——只会表现为识图/聊天静默失败。
 *
 * 幂等：内容一致就不写，不动她的文件时间戳。
 * 只改上面三样，**不碰**她的记忆、人设、会话、prompt。
 *
 * 用法：node tools/sync-koi-api.mjs [--check]
 *   --check 只比对不写，有不一致就退出码 1（给守护插件/体检用）
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';

const CHECK_ONLY = process.argv.includes('--check');
// 路径约定统一在 ops/paths.mjs，这里不再各写一份
const { KOI_HOME, ASU_DSH_HOME, FILES } = await import('../ops/paths.mjs');
const ASU_NAME = ASU_DSH_HOME;

const SRC_PROFILE = FILES.asuPatch;
const SRC_CREDS = FILES.asuCreds;
const DST_PROVIDERS = FILES.koiProviders;
const DST_CREDS = FILES.koiCreds;
const DST_ENV = FILES.koiEnv;
const DST_PATCH = FILES.koiPatch;

function yamlLib() {
  // 依赖在 web profile 的 node_modules 里（dsh 自己的依赖树）
  const candidates = [
    join(ASU_NAME, 'profiles', 'web', 'package.json'),
    FILES.koiProfilePkg,
    join(import.meta.url.replace('file://', '')),
  ];
  for (const c of candidates) {
    try { return createRequire(c)('js-yaml'); } catch { /* 下一个 */ }
  }
  return null;
}

const yaml = yamlLib();
if (!yaml) { console.error('❌ 找不到 js-yaml'); process.exit(2); }

let changed = 0;
const report = [];

function writeIfChanged(file, content, label) {
  const old = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (old === content) { report.push(`= ${label}（一致）`); return; }
  changed += 1;
  if (CHECK_ONLY) { report.push(`✗ ${label}（不一致）`); return; }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content, 'utf8');
  report.push(`✓ ${label}（已同步）`);
}

// ── 1. provider 定义 ──
const srcDoc = yaml.load(readFileSync(SRC_PROFILE, 'utf8'));
const srcRows = Array.isArray(srcDoc) ? srcDoc : [];
const srcProviders = srcRows.find((r) => r?.config?.providers)?.config?.providers ?? {};
if (Object.keys(srcProviders).length === 0) {
  console.error('❌ ashu 的 profile 里没解析到 providers');
  process.exit(2);
}

const providersFile = [
  '# 由 tools/sync-koi-api.mjs 从 ashu 同步生成，勿手改（2026-11-16 主人定：全同步）',
  '# 想改 provider/模型，改 ashu 那边，然后重跑同步或等守护插件同步。',
  // 2026-11-16 **修：必须带 name**。
  // 只写 id+config 时，插入项没有插件名（node_modules 里也没有同名包），
  // 宿主根本加载不到这个插件 → 运行时所有请求报
  // 「no adapter registered for provider "<name>"」，她一个字都说不出来。
  yaml.dump([{ id: 'llm-pi-ai', name: '@deepseek-ai/dsh-llm-pi-ai', config: { providers: srcProviders } }], { lineWidth: -1 }).trimEnd(),
  '',
].join('\n');
writeIfChanged(DST_PROVIDERS, providersFile, 'provider 定义');

/**
 * 2026-11-16 **真正的原因在这里**：
 *
 * 原来 cordis.patch.yml 里写的是 `- !!js "(...)return yaml.load(t)[0]"` ——
 * 一个**裸标量序列项**。patch 列表只认 mapping 和已知指令，这种整条被**静默丢弃**
 * （`dsh --dump-config` 里根本看不到它），于是 llm-pi-ai 从来没配到，
 * 所有请求报 `no adapter registered for provider "<名字>"`。
 *
 * 现在改成把 provider 定义**以普通 YAML 直接写进 patch**，用标记块替换。
 */
const MARK_BEGIN = '# >>> llm-pi-ai (generated by tools/sync-koi-api.mjs, 勿手改) >>>';
const MARK_END = '# <<< llm-pi-ai <<<';
const providersYaml = yaml.dump({ providers: srcProviders }, { lineWidth: -1 })
  .trimEnd()
  .split('\n')
  .map((l) => `    ${l}`)
  .join('\n');
const block = [
  MARK_BEGIN,
  '- id: llm-pi-ai',
  "  name: '@deepseek-ai/dsh-llm-pi-ai'",
  '  config:',
  providersYaml,
  MARK_END,
].join('\n');

const patchSrc = readFileSync(DST_PATCH, 'utf8');
let nextPatch = '';
if (patchSrc.includes(MARK_BEGIN)) {
  const re = new RegExp(`${MARK_BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${MARK_END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);
  // 用函数形式替换：block 里的 $ 序列会被 String.replace 当成替换模式
  nextPatch = patchSrc.replace(re, () => block);
} else {
  // 首次升级：删掉旧的 !!js 那行（以及它前面的说明注释行）
  nextPatch = patchSrc
    .split('\n')
    .filter((l) => !/^-\s*!!js\s+"(?:\(require\('js-yaml'\))/.test(l.trim()))
    .join('\n');
  nextPatch = `${nextPatch.trimEnd()}\n\n${block}\n`;
}
writeIfChanged(DST_PATCH, nextPatch, 'provider 定义（写进 patch）');

// ── 2. 模型选择：优先从 ashu 的 agent-default-model 读，环境变量只作补充 ──
const defaultRow = srcRows.find((r) => r?.id === 'agent-default-model')?.config ?? {};
const chosen = {
  MODEL_PROVIDER: defaultRow.provider ?? process.env.MODEL_PROVIDER ?? '',
  MODEL_NAME: defaultRow.model ?? process.env.MODEL_NAME ?? '',
  MODEL_REASONING_EFFORT: defaultRow.reasoningEffort ?? process.env.MODEL_REASONING_EFFORT ?? '',
};
const MODEL_KEYS = ['MODEL_PROVIDER', 'MODEL_NAME', 'MODEL_REASONING_EFFORT'];
const wantEnv = MODEL_KEYS.filter((k) => chosen[k]).map((k) => `${k}=${chosen[k]}`);
if (wantEnv.length > 0) {
  const oldEnv = existsSync(DST_ENV) ? readFileSync(DST_ENV, 'utf8') : '';
  // 去掉旧的 MODEL_* 行（**含被 # 注释掉的**）和上一次生成的同步段
  const lines = oldEnv.split('\n').filter((l) => {
    if (/^\s*#?\s*(MODEL_PROVIDER|MODEL_NAME|MODEL_REASONING_EFFORT)\s*=/.test(l)) return false;
    // 只要形如「以下由 <谁> 同步」就算标记行，不管里面写的是哪个名字——
    // 老文件用的是别的写法，也不能让它多插一行
    if (l.includes('以下由') && l.includes('同步')) return false;
    return true;
  });
  // 去掉尾部空行，再统一追加
  while (lines.length > 0 && lines[lines.length - 1].trim() === '') lines.pop();
  const body = [...lines, '', '# ── 以下由 ashu 同步 ──', ...wantEnv, ''].join('\n');
  writeIfChanged(DST_ENV, body, '模型选择');
} else {
  report.push('= 模型选择（ashu 进程里没有 MODEL_*，跳过）');
}

// ── 3. 凭据 ──
const needKeys = new Set(
  Object.values(srcProviders)
    .map((p) => p?.apiKeyEnv)
    .filter((k) => typeof k === 'string' && k !== ''),
);
const srcCreds = (() => {
  try { return (yaml.load(readFileSync(SRC_CREDS, 'utf8')) ?? {}).refs ?? {}; }
  catch (e) { console.error('❌ 读 ashu 凭据失败：' + String(e)); return {}; }
})();

let dstCreds = {};
try { dstCreds = (yaml.load(readFileSync(DST_CREDS, 'utf8')) ?? {}); } catch { dstCreds = {}; }
dstCreds.version = dstCreds.version ?? 1;
dstCreds.records = dstCreds.records ?? {};
dstCreds.refs = dstCreds.refs ?? {};

let keyChanged = 0;
const missing = [];
for (const k of needKeys) {
  if (!srcCreds[k]) { missing.push(k); continue; }
  if (dstCreds.refs[k] !== srcCreds[k]) { dstCreds.refs[k] = srcCreds[k]; keyChanged += 1; }
}
if (missing.length > 0) report.push(`⚠️ ashu 也没有这些 key：${missing.join(', ')}`);
if (keyChanged > 0) {
  changed += 1;
  if (CHECK_ONLY) report.push(`✗ 凭据（${keyChanged} 个不一致）`);
  else {
    writeFileSync(DST_CREDS, yaml.dump(dstCreds, { allowUnicode: true }), { mode: 0o600 });
    report.push(`✓ 凭据（同步 ${keyChanged} 个）`);
  }
} else {
  report.push('= 凭据（一致）');
}

for (const line of report) console.log(line);
if (CHECK_ONLY) {
  console.log(changed === 0 ? '\n✅ 已同步' : `\n❌ ${changed} 处不一致`);
  process.exit(changed === 0 ? 0 : 1);
}
console.log(changed === 0 ? '\n无需改动' : `\n完成：${changed} 项已同步`);
